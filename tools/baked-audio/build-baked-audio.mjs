#!/usr/bin/env node
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdir, writeFile, stat } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { pathToFileURL } from "node:url";

const exec = promisify(execFile);

const PROJECT_ROOT = resolve(dirname(new URL(import.meta.url).pathname), "../..");
const OUT_ROOT = resolve(PROJECT_ROOT, "src/clients/mobile-h5/assets/audio/unit-01");
const MANIFEST_PATH = resolve(PROJECT_ROOT, "src/shared/unit-01-baked-audio.js");
const VOICE = "zh-CN-XiaoxiaoNeural";
const RATE = "-10%";
const PITCH = "+0Hz";
const FORCE = process.argv.includes("--force");

const SEGMENT_PLAN = [
  { id: "char", pickText: (item) => item.char },
  { id: "phrase", pickText: (item) => item.phrase || item.words?.[0] || item.char },
  { id: "soundCue", pickText: (item) => item.soundCue || null }
];

async function fileExists(path) {
  try {
    const s = await stat(path);
    return s.size > 0;
  } catch {
    return false;
  }
}

async function generateOne(text, outPath) {
  await mkdir(dirname(outPath), { recursive: true });
  await exec("edge-tts", [
    "--voice", VOICE,
    `--rate=${RATE}`,
    `--pitch=${PITCH}`,
    "--text", text,
    "--write-media", outPath
  ]);
}

async function main() {
  const { unit01 } = await import(pathToFileURL(resolve(PROJECT_ROOT, "src/shared/unit-01.js")).href);
  const characters = unit01.characters;

  const manifest = { voice: VOICE, rate: RATE, pitch: PITCH, generatedAt: new Date().toISOString(), characters: {} };
  let generated = 0;
  let skipped = 0;

  for (const item of characters) {
    const charManifest = {};
    for (const seg of SEGMENT_PLAN) {
      const text = seg.pickText(item);
      if (!text) continue;
      const outPath = resolve(OUT_ROOT, item.id, `${seg.id}.mp3`);
      const relPath = `./assets/audio/unit-01/${item.id}/${seg.id}.mp3`;

      if (!FORCE && (await fileExists(outPath))) {
        charManifest[seg.id] = { src: relPath, text };
        skipped += 1;
        continue;
      }

      process.stdout.write(`[${item.id}] ${seg.id}: ${text}\n`);
      await generateOne(text, outPath);
      charManifest[seg.id] = { src: relPath, text };
      generated += 1;
    }
    manifest.characters[item.id] = charManifest;
  }

  const manifestSource = `// Auto-generated by tools/baked-audio/build-baked-audio.mjs.
// Do not edit by hand. Re-run \`node tools/baked-audio/build-baked-audio.mjs\` to regenerate.
export const unit01BakedAudio = ${JSON.stringify(manifest, null, 2)};
`;
  await writeFile(MANIFEST_PATH, manifestSource, "utf-8");
  process.stdout.write(`\nManifest: ${MANIFEST_PATH}\nGenerated: ${generated} · Skipped: ${skipped}\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
